-- v1.1 (API.md "v1.1 additions"): issue numbers/codes, indexes for search, filters and stats.
-- Applied once by src/migrate.js inside a transaction.

-- Issue number ---------------------------------------------------------------
-- Existing rows are numbered 1..n in created_at order (id breaks ties). The backfill must not
-- touch updated_at, so the updated_at trigger is disabled for the duration of this UPDATE.
ALTER TABLE issues ADD COLUMN number integer;

ALTER TABLE issues DISABLE TRIGGER issues_set_updated_at;
UPDATE issues
   SET number = ordered.n
  FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS n FROM issues) AS ordered
 WHERE issues.id = ordered.id;
ALTER TABLE issues ENABLE TRIGGER issues_set_updated_at;

ALTER TABLE issues ALTER COLUMN number SET NOT NULL;
ALTER TABLE issues ALTER COLUMN number ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('issues', 'number'), COALESCE(max(number), 0) + 1, false) FROM issues;
ALTER TABLE issues ADD CONSTRAINT issues_number_key UNIQUE (number);
ALTER TABLE issues ADD CONSTRAINT issues_number_positive CHECK (number > 0);

-- Filters ----------------------------------------------------------------------
CREATE INDEX issues_campus_priority_created_idx ON issues (campus_id, priority, created_at DESC);
CREATE INDEX issues_assigned_to_idx             ON issues (assigned_to);
CREATE INDEX issues_campus_resolved_at_idx      ON issues (campus_id, resolved_at) WHERE resolved_at IS NOT NULL;

-- Search (q): case-insensitive substring match via ILIKE, served by trigram indexes.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX issues_title_trgm_idx           ON issues USING gin (title gin_trgm_ops);
CREATE INDEX issues_location_detail_trgm_idx ON issues USING gin (location_detail gin_trgm_ops);

